u_short SsPitchFromNote(short note, short fine, u_char center, u_char shift) {
    short sum = shift + fine;
    int carry = sum / 128;
    short n = note + carry - center;
    short frac = sum - carry * 128;
    short oct, octave, scale;
    unsigned pitch;

    if (frac < 0) {
        frac += 0x80;
        n = n - 1 + frac / 128;
    }
    oct = n / 12;
    octave = oct - 2;
    scale = n % 12;
    if (scale < 0) {
        scale += 12;
        octave = oct - 3;
    }
    pitch = (semitone_table[scale] * fine_table[frac]) >> 16;
    if (octave >= 0) {
        return 0x3FFF;
    }
    pitch += 1u << (-octave - 1);
    return pitch >> -octave;
}

unsigned short note2pitch(void) {
    return SsPitchFromNote(
        _svm_cur.note, 0, (u8)_svm_cur.tone_center, (u8)_svm_cur.tone_shift);
}

unsigned short note2pitch2(unsigned short note, unsigned short fine) {
    s16 tone = _svm_cur.fake_program * 16 + _svm_cur.tone;

    return SsPitchFromNote(
        (short)note, (short)fine, _svm_tn[tone].center, _svm_tn[tone].shift);
}
